const fs = require("node:fs");
const path = require("node:path");

const { expect, test } = require(path.resolve(
  __dirname,
  "../../../frontend/node_modules/@playwright/test",
));

// Drives the unmodified frozen frontend against the real Haifa gateway and the
// controlled loopback provider. It never mocks the page or the protocol: the
// auto-title travels through the real Run/SSE/metadata path and the follow-up
// suggestions through the real POST /api/threads/{id}/suggestions call.
const APP =
  process.env.E2E_APP_URL ??
  `http://127.0.0.1:${process.env.E2E_FRONTEND_PORT ?? "45618"}`;
const EXPECTED_SUGGESTIONS = ["What changed?", "Why now?", "What next?"];

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

async function pollRun(request, threadId, runId, expectedStatus) {
  const url = `${APP}/api/langgraph/threads/${encodeURIComponent(threadId)}/runs/${encodeURIComponent(runId)}`;
  let latest;
  await expect
    .poll(
      async () => {
        const response = await request.get(url);
        expect(response.status(), await response.text()).toBe(200);
        latest = await response.json();
        return latest.status;
      },
      { timeout: 30_000, intervals: [50, 100, 250] },
    )
    .toBe(expectedStatus);
  return latest;
}

async function saveEvidence(testInfo, name, evidence) {
  const file = testInfo.outputPath(`${name}.json`);
  fs.writeFileSync(file, `${JSON.stringify(evidence, null, 2)}\n`, "utf8");
  await testInfo.attach(`${name}.json`, {
    path: file,
    contentType: "application/json",
  });
}

test.describe("W03 frozen UI title + suggestions", () => {
  test("first exchange names the thread and renders provider suggestions", async ({
    context,
    page,
  }, testInfo) => {
    const prompt = `w03-title-suggestions-${Date.now()}`;
    const configPromise = page.waitForResponse(
      (response) =>
        response.request().method() === "GET" &&
        new URL(response.url()).pathname === "/api/suggestions/config",
    );
    const streamPromise = page.waitForResponse(
      (response) =>
        response.request().method() === "POST" &&
        /\/api\/langgraph\/threads\/[^/]+\/runs\/stream$/.test(
          new URL(response.url()).pathname,
        ),
    );
    const suggestionsPromise = page.waitForResponse(
      (response) =>
        response.request().method() === "POST" &&
        /\/api\/threads\/[^/]+\/suggestions$/.test(
          new URL(response.url()).pathname,
        ),
    );

    await page.goto("/workspace/chats/new", { waitUntil: "domcontentloaded" });
    const input = page.locator('textarea[name="message"]');
    await expect(input).toBeVisible();
    await input.fill(prompt);
    await input.press("Enter");

    const streamResponse = await streamPromise;
    expect(streamResponse.status(), await streamResponse.text()).toBe(200);
    const location = streamResponse.headers()["content-location"];
    expect(location, "run stream must expose Content-Location").toBeTruthy();
    const identityMatch = location.match(/\/api\/threads\/([^/]+)\/runs\/([^/]+)$/);
    expect(identityMatch, `unexpected run location: ${location}`).toBeTruthy();
    const [, threadId, runId] = identityMatch;

    await expect(page).toHaveURL(new RegExp(`/workspace/chats/${threadId}$`));
    await pollRun(context.request, threadId, runId, "success");

    // Auto title: the frozen header and document title read the gateway's
    // values.title projection for the first user Turn.
    await expect(page.locator("header").getByText(prompt, { exact: true })).toBeVisible({
      timeout: 30_000,
    });
    await expect(page).toHaveTitle(new RegExp(`^${escapeRegExp(prompt)} - `), {
      timeout: 30_000,
    });

    // Suggestions config consumed from the real gateway.
    const configResponse = await configPromise;
    expect(configResponse.status(), await configResponse.text()).toBe(200);
    const config = await configResponse.json();
    expect(config).toMatchObject({ enabled: true, max_suggestions: 3 });

    // Suggestions generated by the controlled provider through the real endpoint.
    const suggestionsResponse = await suggestionsPromise;
    expect(suggestionsResponse.status(), await suggestionsResponse.text()).toBe(200);
    const suggestionsBody = await suggestionsResponse.json();
    expect(suggestionsBody.suggestions).toEqual(EXPECTED_SUGGESTIONS);

    const list = page.locator('[data-slot="suggestions-list"]');
    await expect(list).toBeVisible({ timeout: 20_000 });
    for (const suggestion of EXPECTED_SUGGESTIONS) {
      await expect(
        list.getByRole("button", { name: suggestion, exact: true }),
      ).toBeVisible();
    }

    const screenshot = testInfo.outputPath("w03-title-suggestions.png");
    await page.screenshot({ path: screenshot, fullPage: true });
    await testInfo.attach("w03-title-suggestions.png", {
      path: screenshot,
      contentType: "image/png",
    });
    await saveEvidence(testInfo, "w03-title-suggestions", {
      prompt,
      threadId,
      runId,
      documentTitle: await page.title(),
      headerTitle: await page.locator("header").innerText(),
      suggestionConfig: config,
      suggestions: suggestionsBody.suggestions,
      suggestionsEndpoint: suggestionsResponse.url(),
    });
  });

  test("explicit rename wins and survives a reload", async ({
    context,
    page,
  }, testInfo) => {
    const prompt = `w03-title-rename-${Date.now()}`;
    const renamed = `Renamed ${Date.now()}`;
    const streamPromise = page.waitForResponse(
      (response) =>
        response.request().method() === "POST" &&
        /\/api\/langgraph\/threads\/[^/]+\/runs\/stream$/.test(
          new URL(response.url()).pathname,
        ),
    );

    await page.goto("/workspace/chats/new", { waitUntil: "domcontentloaded" });
    const input = page.locator('textarea[name="message"]');
    await expect(input).toBeVisible();
    await input.fill(prompt);
    await input.press("Enter");
    const streamResponse = await streamPromise;
    expect(streamResponse.status(), await streamResponse.text()).toBe(200);
    const location = streamResponse.headers()["content-location"];
    const identityMatch = location.match(/\/api\/threads\/([^/]+)\/runs\/([^/]+)$/);
    const [, threadId, runId] = identityMatch;
    await pollRun(context.request, threadId, runId, "success");
    await expect(page.locator("header").getByText(prompt, { exact: true })).toBeVisible({
      timeout: 30_000,
    });

    // Rename through the frozen sidebar menu; the dialog writes POST /state.
    const renameResponsePromise = page.waitForResponse(
      (response) =>
        response.request().method() === "POST" &&
        new URL(response.url()).pathname.endsWith(
          `/api/langgraph/threads/${threadId}/state`,
        ),
    );
    const threadItem = page
      .locator(
        `a[data-sidebar="menu-button"][href="/workspace/chats/${threadId}"]`,
      )
      .locator("xpath=..");
    await threadItem.hover();
    await threadItem.getByRole("button", { name: "More" }).click();
    await page.getByRole("menuitem", { name: "Rename" }).click();
    const dialog = page.getByRole("dialog");
    await dialog.getByRole("textbox").fill(renamed);
    await dialog.getByRole("button", { name: "Save" }).click();
    const renameResponse = await renameResponsePromise;
    expect(renameResponse.status(), await renameResponse.text()).toBe(200);

    await expect(page.locator("header").getByText(renamed, { exact: true })).toBeVisible();
    await page.reload({ waitUntil: "domcontentloaded" });
    await expect(page.locator("header").getByText(renamed, { exact: true })).toBeVisible({
      timeout: 30_000,
    });
    await expect(page).toHaveTitle(new RegExp(`^${escapeRegExp(renamed)} - `), {
      timeout: 30_000,
    });

    await saveEvidence(testInfo, "w03-title-rename", {
      prompt,
      threadId,
      renamed,
      renameStatus: renameResponse.status(),
      documentTitle: await page.title(),
    });
  });
});
